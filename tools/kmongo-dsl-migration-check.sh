check DEPRECATED "MongoIterable.into(...) / iterator() / for loops on a MongoIterable" \
  "deprecated compatibility functions are provided: use toCollection(...), toList(), forEach { } or cursor().use { }" \
  sync_files '\.into\(|\.iterator\(\)'

check FIX "import org.litote.kmongo.withDocumentClass" \
  "withDocumentClass<T>() is a member of the driver collection: remove the import" \
  kotlin_files '^import org\.litote\.kmongo\.withDocumentClass$'

check DEPRECATED "org.litote.kmongo.reactivestreams (KMongo 4/5 reactive streams flavor)" \
  "deprecated compatibility functions are provided: use org.litote.kmongo.coroutine.* (and remove .coroutine) - do not star import both packages" \
  kotlin_files '^import org\.litote\.kmongo\.reactivestreams\.'

check DEPRECATED "KMongo 4/5 coroutine wrappers (CoroutineCollection, CoroutineDatabase, .coroutine...)" \
  "deprecated type aliases are provided: use the official driver classes (IDE quick fix 'Replace with...')" \
  kotlin_files '\bCoroutine(Client|Database|Collection|FindPublisher|AggregatePublisher|DistinctPublisher|ChangeStreamPublisher)\b|\.coroutine([^.A-Za-z0-9_]|$)'

check REVIEW "watch / change stream helpers: the driver resumes once only" \
  "use watchIndefinitely() (coroutine) or listenIndefinitely() (sync) to survive the errors and the invalidations" \
  kotlin_files '\.watch(<[^>]*>)?\('

check REVIEW "dropIndex with JSON keys: the driver function takes the name of the index (NOT detected by the compiler)" \
  "use dropIndexOfKeys(...)" \
  kotlin_files '\.dropIndex\(([^"]*,\s*)?"\s*\{'

check FIX "map-reduce (removed)" \
  "use an aggregation pipeline" \
  kotlin_files '\bmapReduce(With)?\b'

check FIX "legacy DBObject API (not supported)" \
  "use Document or Map" \
  kotlin_files '\b(Basic)?DBObject\b'

check FIX "MongoClientProvider SPI (removed)" \
  "create the client with KMongo.createClient(...)" \
  kotlin_files '\bMongoClientProvider(Service)?\b'

check REVIEW "GridFS (not provided by the Kotlin driver)" \
  "use the Java client: KMongo.createJavaClient(...) + KMongo.createClient(javaClient) to share the connection pool" \
  kotlin_files '\bGridFS(Bucket|Buckets)?\b'

check REVIEW "static mocks of KMongo extensions (the JVM file classes have changed: CoroutineCollectionKt...)" \
  "prefer tests against a real server (kmongo-dsl-testcontainers)" \
  kotlin_files 'mockkStatic\(.*(org\.litote\.kmongo|Coroutine[A-Za-z]*Kt)'

check FIX "kmongo-flapdoodle (no equivalent)" \
  "use org.litote.kmongo:kmongo-dsl-testcontainers (KMongoTestServer.connectionString)" \
  build_files 'kmongo-flapdoodle|flapdoodle'

check FIX "kmongo-annotation-processor (KAPT)" \
  "use org.litote.kmongo:kmongo-dsl-annotation-processor (KAPT, Maven) or kmongo-dsl-ksp (KSP, Gradle)" \
  build_files 'kmongo-annotation-processor'

check FIX "jackson-generator (KAPT, KotlinPoet 1.0 - conflicts with kmongo-dsl-annotation-processor)" \
  "use org.litote.kmongo:kmongo-dsl-annotation-generator (same annotations, same generated serializers)" \
  build_files '(<artifactId>|org\.litote\.jackson:)jackson-generator\b'

check FIX "jackson-data, jackson-module-loader (same classes as the kmongo-dsl-* artifacts)" \
  "use org.litote.kmongo:kmongo-dsl-jackson-data and org.litote.kmongo:kmongo-dsl-jackson-module-loader (same packages)" \
  build_files '(<artifactId>|org\.litote\.jackson:)jackson-(data|module-loader)\b'

check FIX "Jackson 2 API (the Jackson mapping uses Jackson 3)" \
  "migrate to the tools.jackson packages: the Jackson 2 modules, serializers and mappers are not used by KMongo DSL (see the migration guide) - the com.fasterxml.jackson.annotation annotations are unchanged" \
  kotlin_files '^import com\.fasterxml\.jackson\.(core|databind|module|datatype)\b'

check REVIEW "kreflect (used by the code generated by kmongo-annotation-processor and jackson-generator)" \
  "not used by the code generated by kmongo-dsl-annotation-processor and kmongo-dsl-annotation-generator: remove it if unused" \
  build_files '(<artifactId>|org\.litote:)kreflect\b'

check FIX "KMongo 4/5 artifacts" \
  "use the kmongo-dsl-* artifacts (see the migration guide table) - kmongo-id, kmongo-data... are replaced by kmongo-dsl-id, kmongo-dsl-data..." \
  build_files '(<artifactId>|org\.litote\.kmongo:)kmongo(-(coroutine|async|rxjava2|reactor|native|serialization|core|shared|property|jackson-mapping|serialization-mapping|native-mapping|coroutine-core|coroutine-serialization|async-serialization|reactor-serialization|rxjava2-serialization|id|data|id-jackson|id-serialization))?(</artifactId>|[:"])' 

if [ $found -eq 0 ]; then
  echo "Nothing to review."
fi
exit $found
