# --add-imports: the kmongo-dsl extensions are not in the packages of the driver classes,
# the files with explicit imports (ktlint) need an import for each extension.
if [ -n "$add_imports" ]; then
  KMONGO_DSL_SYMBOLS="$KMONGO_DSL_SYMBOLS" perl -e '
    my ($log) = @ARGV;
    # name -> packages
    my %packages;
    for my $line (split /\n/, $ENV{KMONGO_DSL_SYMBOLS}) {
      my ($package, @names) = split / /, $line;
      next unless $package;
      push @{$packages{$_}}, $package for @names;
    }
    # file -> unresolved names, from the Kotlin compiler output (K1 and K2 formats, Gradle and Maven)
    my (%unresolved, $file);
    open(my $in, "<", $log) or die "$log: $!";
    while (my $line = <$in>) {
      # the following lines of a message (candidates...) belong to the file of the message
      if ($line =~ m{(?:file://)?(/[^\s:]+\.kt)\b}) { $file = $1; }
      elsif ($line =~ /^(?:w: |> |\* |BUILD |FAILURE|\[(?:INFO|WARNING)\])/) { undef $file; }
      next unless $file;
      my @names;
      push @names, $1 if $line =~ /Unresolved reference(?::\s*|\s+\x27)`?([A-Za-z_]\w*)/;
      push @names, $1 if $line =~ /has no method \x27(\w+)\(/;
      push @names, "iterator" if $line =~ /must have an \x27iterator\(\)\x27 method/;
      # receiver type mismatch: the name is in the candidates of the following lines
      push @names, $1 if $line =~ /^\s*(?:\[ERROR\]\s*)?(?:public\s+)?(?:(?:inline|suspend|infix|operator)\s+)*(?:fun|val|var)\s+(?:<[^(]*?>\s+)?[\w.<>?, *]*?\.?(\w+)\s*[(:]/;
      # lambda passed to a member function (find().filter { }): the extension function is not imported,
      # the name is read in the source file at the error position
      if ($line =~ /\.kt:(?:\[(\d+),\s*(\d+)\]|(\d+):(\d+)):?\s+Argument type mismatch: actual type is \x27[^\x27]*->/) {
        my ($row, $column) = (defined $1 ? ($1, $2) : ($3, $4));
        if (open(my $source, "<", $file)) {
          my @source = <$source>;
          push @names, $1 if defined $source[$row - 1] && substr($source[$row - 1], 0, $column - 1) =~ /(\w+)\s*$/;
        }
      }
      $unresolved{$file}{$_} = 1 for grep { exists $packages{$_} } @names;
    }
    my $added = 0;
    for my $file (sort keys %unresolved) {
      next unless -f $file;
      open(my $fh, "<", $file) or die "$file: $!";
      my @lines = <$fh>;
      close $fh;
      my $content = join "", @lines;
      my $coroutine = $content =~ /^import (?:com\.mongodb\.kotlin\.client\.coroutine|org\.litote\.kmongo\.coroutine)\./m;
      my @imports;
      for my $name (sort keys %{$unresolved{$file}}) {
        my @candidates = @{$packages{$name}};
        my ($package) = grep { $_ eq ($coroutine ? "org.litote.kmongo.coroutine" : "org.litote.kmongo") } @candidates;
        ($package) = grep { $_ eq "org.litote.kmongo" } @candidates unless $package;
        $package = $candidates[0] if !$package && @candidates == 1;
        if (!$package) { print "$file: $name is ambiguous (", join(", ", @candidates), "): add the import manually\n"; next; }
        next if $content =~ /^import \Q$package\E\.(?:\Q$name\E|\*)\s*$/m;
        push @imports, "import $package.$name\n";
      }
      next unless @imports;
      # insertion in the sorted imports (before the java, javax, kotlin and alias imports - IntelliJ / ktlint layout)
      for my $import (@imports) {
        my ($last, $position) = (-1, -1);
        for my $i (0 .. $#lines) {
          next unless $lines[$i] =~ /^import /;
          $last = $i;
          next if $lines[$i] =~ /^import (?:java|javax|kotlin)\.|\sas\s/;
          if ($position < 0 && $lines[$i] gt $import) { $position = $i; }
        }
        if ($position < 0) {
          # after the last "main" import, or after the package line
          $position = -1;
          for my $i (0 .. $#lines) { $position = $i + 1 if $lines[$i] =~ /^import / && $lines[$i] !~ /^import (?:java|javax|kotlin)\.|\sas\s/; }
          if ($position < 0) {
            for my $i (0 .. $#lines) { if ($lines[$i] =~ /^package /) { $position = $i + 1; splice @lines, $position++, 0, "\n"; last; } }
            $position = 0 if $position < 0;
          }
        }
        splice @lines, $position, 0, $import;
        $added++;
      }
      open(my $out, ">", $file) or die "$file: $!";
      print $out @lines;
      close $out;
      print "$file: ", scalar(@imports), " import(s) added\n";
    }
    print "$added import(s) added", ($added ? " - compile again and rerun until no import is added" : ""), "\n";
  ' "$add_imports"
  exit $?
fi

SYNC_TYPES='MongoClient|MongoDatabase|MongoCollection|FindIterable|AggregateIterable|DistinctIterable|MongoIterable|MongoCursor|ClientSession|ChangeStreamIterable|ListIndexesIterable'

kotlin_files() { find "${dirs[@]}" -type f -name '*.kt' -not -path '*/build/*' -not -path '*/target/*' -not -path '*/.gradle/*'; }
build_files() { find "${dirs[@]}" -type f \( -name 'pom.xml' -o -name '*.gradle' -o -name '*.gradle.kts' -o -name '*.toml' \) -not -path '*/build/*' -not -path '*/target/*'; }

if $fix_imports; then
  kotlin_files | xargs -r grep -lE "^import com\.mongodb\.client\.($SYNC_TYPES)$" | xargs -r sed -i -E \
    "s/^import com\.mongodb\.client\.($SYNC_TYPES)$/import com.mongodb.kotlin.client.\1/"
  echo "Java sync driver imports replaced by the Kotlin sync driver imports."
  echo
fi

found=0

# check <severity> <title> <advice> <files command> <regex>
check() {
  local severity="$1" title="$2" advice="$3" files="$4" regex="$5" result
  result=$($files | xargs -r grep -HnE "$regex" 2>/dev/null)
  if [ -n "$result" ]; then
    found=1
    echo "[$severity] $title"
    echo "    -> $advice"
    echo "$result" | sed 's/^/    /'
    echo
  fi
}

# the sync files (Java or Kotlin sync driver imports)
sync_files() { kotlin_files | xargs -r grep -lE '^import com\.mongodb\.(kotlin\.)?client\.(MongoCollection|MongoDatabase|FindIterable|AggregateIterable|MongoIterable|DistinctIterable)$'; }

echo "KMongo DSL migration check of: ${dirs[*]}"
echo

# check_perl <severity> <title> <advice> <files command> <perl statement regex>: the statements (lines joined with
# the following ".xxx" continuation lines) matching the regex
check_perl() {
  local severity="$1" title="$2" advice="$3" files="$4" regex="$5" result
  result=$($files | xargs -r perl -e '
    my $regex = shift;
    for my $file (@ARGV) {
      open(my $in, "<", $file) or next;
      my @lines = <$in>;
      my ($i, $n) = (0, scalar @lines);
      while ($i < $n) {
        my ($start, $statement) = ($i, $lines[$i]);
        while ($i + 1 < $n && $lines[$i + 1] =~ /^\s*(?:\?\.|\.)/) { $statement .= $lines[++$i]; }
        if ($statement =~ /$regex/) {
          (my $text = $statement) =~ s/\s*\n\s*/ /g;
          $text =~ s/^\s+|\s+$//g;
          print "$file:", $start + 1, ": $text\n";
        }
        $i++;
      }
    }' "$regex" 2>/dev/null)
  if [ -n "$result" ]; then
    found=1
    echo "[$severity] $title"
    echo "    -> $advice"
    echo "$result" | sed 's/^/    /'
    echo
  fi
}

# the driver calls returning an iterable (and their modifiers), with one level of nested parentheses
ITERABLE_CALL='\b(?:find|aggregate|distinct|listIndexes|listCollections|listCollectionNames|listDatabases|listDatabaseNames|projection|sort|limit|skip|filter|batchSize|hint|hintString|maxTime|maxAwaitTime|collation|comment|partial|noCursorTimeout|allowDiskUse|showRecordId|returnKey|let|min|max|descendingSort|ascendingSort|cursorType)(?:<[^<>]*(?:<[^<>]*>[^<>]*)*>)?\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)'

check_perl REVIEW "sync first(): returned null if there was no result, now throws a MongoClientException (NOT detected by the compiler)" \
  "use firstOrNull() - keep first() only if a result is guaranteed (first() on a variable holding a FindIterable is not detected)" \
  sync_files "${ITERABLE_CALL}\\s*\\.first\\(\\)"

