#!/usr/bin/env bash
#
# KMongo 4/5 -> KMongo DSL migration check.
#
# Lists the code that needs a review when migrating from KMongo 4/5 to KMongo DSL,
# in particular the changes that the compiler does NOT detect (sync first(), ...).
# See docs/migration-kmongo-to-kmongo-dsl.md.
#
# Usage: kmongo-dsl-migration-check.sh [--fix-imports] [--add-imports <compiler output>] [directory...]
#        (default directory: the current directory)
#   --fix-imports        replaces the Java sync driver imports by the Kotlin sync driver imports (sed -i)
#   --add-imports <log>  adds the explicit imports of the kmongo-dsl extensions reported as unresolved
#                        in the compiler output <log> (Gradle or Maven), then exits.
#                        Compile, run, repeat until no import is added: mvn compile > build.log; $0 --add-imports build.log
#
# Exit code: 0 if nothing has to be reviewed, 1 otherwise.

set -uo pipefail

fix_imports=false
add_imports=""
dirs=()
while [ $# -gt 0 ]; do
  case "$1" in
    --fix-imports) fix_imports=true ;;
    --add-imports) add_imports="${2:?--add-imports requires the compiler output file}"; shift ;;
    -h|--help) sed -n '3,18p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) dirs+=("$1") ;;
  esac
  shift
done
[ ${#dirs[@]} -eq 0 ] && dirs=(.)

