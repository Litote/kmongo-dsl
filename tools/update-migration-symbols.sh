#!/usr/bin/env bash
#
# Updates the index of the kmongo-dsl public top-level declarations embedded in kmongo-dsl-migration-check.sh
# (used by its --add-imports option).
#
# Usage: tools/update-migration-symbols.sh [--check]
#   --check  fails if the embedded index is not up to date (CI)

set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
script="$root/tools/kmongo-dsl-migration-check.sh"
modules=(core sync coroutine jackson-mapping serialization-mapping)

sources=()
for module in "${modules[@]}"; do
  while IFS= read -r file; do sources+=("$file"); done < <(find "$root/$module/src/main/kotlin" -name '*.kt' | sort)
done

# one line per package: "<package> <name> <name>..."
symbols=$(perl -e '
  my %symbols;
  for my $file (@ARGV) {
    open(my $in, "<", $file) or die "$file: $!";
    my $package = "";
    while (my $line = <$in>) {
      if ($line =~ /^package\s+([\w.]+)/) { $package = $1; next; }
      next unless $line =~ /^public\s+(?:(?:inline|suspend|infix|operator|tailrec|const|data|enum|sealed|abstract|open|annotation|value|external)\s+)*(fun\s+interface|fun|val|var|object|class|interface|typealias)\s+(.*)$/;
      my ($keyword, $rest) = ($1, $2);
      my $name;
      if ($keyword =~ /^(fun|val|var)$/) {
        # skip the type parameters, the name is the last identifier before "(" (fun) or ":" / "=" (val, var)
        my ($depth, $text) = (0, "");
        for my $char (split //, $rest) {
          if ($char eq "<") { $depth++; }
          elsif ($char eq ">") { $depth--; }
          elsif ($depth == 0 && ($keyword eq "fun" ? $char eq "(" : $char =~ /[:=]/)) { last; }
          $text .= $char;
        }
        $text =~ s/^\s*<.*?>\s*//;
        ($name) = $text =~ /`?([A-Za-z_][A-Za-z0-9_]*)`?\s*$/;
      } else {
        ($name) = $rest =~ /^`?([A-Za-z_][A-Za-z0-9_]*)/;
      }
      $symbols{$package}{$name} = 1 if $name && $package;
    }
  }
  for my $package (sort keys %symbols) {
    print "$package ", join(" ", sort keys %{$symbols{$package}}), "\n";
  }
' "${sources[@]}")

begin="# BEGIN KMONGO_DSL SYMBOLS (generated by tools/update-migration-symbols.sh - do not edit)"
end="# END KMONGO_DSL SYMBOLS"
updated=$(perl -0pe '
  BEGIN { ($begin, $end, $symbols) = (shift, shift, shift); }
  s/\Q$begin\E\n.*?\Q$end\E/$begin\nKMONGO_DSL_SYMBOLS="\n$symbols\n"\n$end/s
' "$begin" "$end" "$symbols" "$script")

if [ "${1:-}" = "--check" ]; then
  if [ "$updated" != "$(cat "$script")" ]; then
    echo "The kmongo-dsl symbols of $script are not up to date: run tools/update-migration-symbols.sh" >&2
    exit 1
  fi
  echo "The kmongo-dsl symbols are up to date."
else
  printf '%s\n' "$updated" > "$script"
  echo "kmongo-dsl symbols updated in $script ($(printf '%s\n' "$symbols" | wc -l) packages)."
fi
