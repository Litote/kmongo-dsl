package org.litote.kmongo.sample

import org.litote.kmongo.eq
import org.litote.kmongo.json
import org.litote.kmongo.util.KMongoConfiguration
import kotlin.test.Test
import kotlin.test.assertEquals

class FriendPathTest {

    @Test
    fun `property paths generated by the KAPT processor`() {
        assertEquals("address.city", Friend_.Address.city.name)
        assertEquals("previousAddresses.\$.city", Friend_.PreviousAddresses.posOp.city.name)
        assertEquals("tags.home.zipCode", Friend_.Tags.keyProjection("home").zipCode.name)
        assertEquals("""{"address.city": "Paris"}""", (Friend_.Address.city eq "Paris").json)
    }

    @Test
    fun `Jackson serializers generated by the KAPT processor`() {
        val mapper = KMongoConfiguration.bsonMapper
        assertEquals(
            "Friend_Serializer",
            mapper._serializationContext().findValueSerializer(Friend::class.java).javaClass.simpleName,
        )
        val friend = Friend("Joe", Address("Paris"), tags = mapOf("home" to Address("Lyon", "69000")))
        assertEquals(friend, mapper.readValue(mapper.writeValueAsBytes(friend), Friend::class.java))
    }
}
