import org.jetbrains.kotlin.gradle.dsl.KotlinVersion
import org.jetbrains.kotlin.gradle.dsl.abi.ExperimentalAbiValidation

plugins {
    id("kmongo-dsl.kotlin-jvm")
    id("kmongo-dsl.publishing")
    id("org.jetbrains.dokka")
    id("org.jetbrains.dokka-javadoc")
}

kotlin {
    // published API: visibility & return types must be explicit
    explicitApi()

    // The published artifacts require Kotlin 2.4+: kotlin-reflect 2.2 makes the Jackson Kotlin module allocate
    // much more, and the published libraries bring the reflect version of the consumers.
    compilerOptions {
        languageVersion.set(KotlinVersion.KOTLIN_2_4)
        apiVersion.set(KotlinVersion.KOTLIN_2_4)
    }

    // Binary compatibility of the published API: checkKotlinAbi (run by `check`) compares the API with the
    // reference dump (api/<module>.api). After an intended API change: ./gradlew updateKotlinAbi
    @OptIn(ExperimentalAbiValidation::class)
    abiValidation()
}


mavenPublishing {
    // javadoc jar generated by Dokka
    configure(
        com.vanniktech.maven.publish.KotlinJvm(
            javadocJar = com.vanniktech.maven.publish.JavadocJar.Dokka("dokkaGeneratePublicationJavadoc"),
            sourcesJar = true,
        )
    )
}
