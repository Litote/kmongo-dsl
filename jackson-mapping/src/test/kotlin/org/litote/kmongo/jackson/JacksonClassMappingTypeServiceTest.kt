package org.litote.kmongo.jackson

import com.fasterxml.jackson.annotation.JsonProperty
import org.bson.codecs.pojo.annotations.BsonId
import org.litote.kmongo.util.KMongoConfiguration
import tools.jackson.core.JsonGenerator
import tools.jackson.databind.SerializationContext
import tools.jackson.databind.ValueSerializer
import tools.jackson.databind.module.SimpleModule
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 *
 */
class JacksonClassMappingTypeServiceTest {

    data class AnnotatedData(@JsonProperty("other") val property: String, @BsonId val key: String)

    data class CustomSerializedData(val name: String, val description: String?, val _id: String)

    /** Writes all the properties itself, like the serializers generated by jackson-data. */
    class CustomSerializedDataSerializer : ValueSerializer<CustomSerializedData>() {
        override fun serialize(value: CustomSerializedData, gen: JsonGenerator, ctxt: SerializationContext) {
            gen.writeStartObject()
            gen.writeStringProperty("name", value.name)
            gen.writeName("description")
            if (value.description == null) gen.writeNull() else gen.writeString(value.description)
            gen.writeStringProperty("_id", value._id)
            gen.writeEndObject()
        }
    }

    @AfterTest
    fun resetConfiguration() {
        KMongoConfiguration.resetConfiguration()
    }

    @Test
    fun `filterIdToBson removes the id written by a custom serializer`() {
        KMongoConfiguration.registerBsonModule(
            SimpleModule().addSerializer(CustomSerializedData::class.java, CustomSerializedDataSerializer())
        )
        val service = JacksonClassMappingTypeService()
        val data = CustomSerializedData("name", null, "id")

        assertEquals(
            """{"name": "name", "description": null}""",
            service.filterIdToBson(data, filterNullProperties = false).toJson()
        )
        assertEquals(
            """{"name": "name", "description": null}""",
            service.filterIdToBson(data, filterNullProperties = true).toJson()
        )
    }

    @Test
    fun `getPath handles well @JsonProperty and @BsonId`() {
        val service = JacksonClassMappingTypeService()
        assertEquals(
            "other",
            service.getPath(AnnotatedData::property)
        )
        assertEquals(
            "_id",
            service.getPath(AnnotatedData::key)
        )
    }
}
