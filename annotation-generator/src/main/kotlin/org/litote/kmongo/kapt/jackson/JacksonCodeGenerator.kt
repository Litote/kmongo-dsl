package org.litote.kmongo.kapt.jackson

import com.squareup.kotlinpoet.ANY
import com.squareup.kotlinpoet.BOOLEAN
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MAP
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterizedTypeName
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.joinToCode

/**
 * Generates the Jackson serializer (`MyClass_Serializer`) and deserializer (`MyClass_Deserializer`) of a
 * `@JacksonData` class - the same classes as the ones generated by `org.litote.jackson:jackson-generator`.
 *
 * The generated classes implement `org.litote.jackson.JacksonModuleServiceLoader`: they are registered
 * in `META-INF/services` and loaded by the kmongo-dsl Jackson mapping.
 */
internal object JacksonCodeGenerator {

    private const val JACKSON_CORE = "tools.jackson.core"
    private const val JACKSON_DATABIND = "tools.jackson.databind"
    private const val KOTLIN_REFLECT = "kotlin.reflect"
    private const val KOTLIN_REFLECT_FULL = "kotlin.reflect.full"

    private val JSON_GENERATOR = ClassName(JACKSON_CORE, "JsonGenerator")
    private val JSON_PARSER = ClassName(JACKSON_CORE, "JsonParser")
    private val JSON_TOKEN = ClassName(JACKSON_CORE, "JsonToken")
    private val TYPE_REFERENCE = ClassName("tools.jackson.core.type", "TypeReference")
    private val SERIALIZER_PROVIDER = ClassName(JACKSON_DATABIND, "SerializationContext")
    private val DESERIALIZATION_CONTEXT = ClassName(JACKSON_DATABIND, "DeserializationContext")
    private val JSON_DESERIALIZER = ClassName(JACKSON_DATABIND, "ValueDeserializer")
    private val MODULE = ClassName(JACKSON_DATABIND, "JacksonModule")
    private val SIMPLE_MODULE = ClassName("tools.jackson.databind.module", "SimpleModule")
    private val STD_SERIALIZER = ClassName("tools.jackson.databind.ser.std", "StdSerializer")
    private val MODULE_LOADER = ClassName("org.litote.jackson", "JacksonModuleServiceLoader")
    private val K_FUNCTION = ClassName(KOTLIN_REFLECT, "KFunction")
    private val K_PARAMETER = ClassName(KOTLIN_REFLECT, "KParameter")
    private val K_PROPERTY1 = ClassName(KOTLIN_REFLECT, "KProperty1")
    private val PRIMARY_CONSTRUCTOR = MemberName(KOTLIN_REFLECT_FULL, "primaryConstructor")
    private val FIND_PARAMETER_BY_NAME = MemberName(KOTLIN_REFLECT_FULL, "findParameterByName")
    private val DECLARED_MEMBER_PROPERTIES = MemberName(KOTLIN_REFLECT_FULL, "declaredMemberProperties")
    private val IS_ACCESSIBLE = MemberName("kotlin.reflect.jvm", "isAccessible")
    private const val LAZY_MODE = "LazyThreadSafetyMode.PUBLICATION"

    /** The name of the generated serializer of a class. */
    fun serializerName(className: ClassName): ClassName =
        ClassName(className.packageName, "${className.simpleName}_Serializer")

    /** The name of the generated deserializer of a class. */
    fun deserializerName(className: ClassName): ClassName =
        ClassName(className.packageName, "${className.simpleName}_Deserializer")

    // the property variables start with "_": no conflict with the other variables (token_, result_...)
    private val JacksonPropertyModel.local: String get() = "_${name}_"
    private val JacksonPropertyModel.setFlag: String get() = "_${name}_set"
    private val JacksonPropertyModel.reference: String get() = "_${name}__reference"
    private val JacksonPropertyModel.reflectedProperty: String get() = "_${name}__property"

    /** The serializer source file. */
    fun serializer(model: JacksonClassModel): FileSpec {
        val source = model.className
        val name = serializerName(source)
        val type = TypeSpec.classBuilder(name)
            .addModifiers(KModifier.INTERNAL)
            .superclass(STD_SERIALIZER.parameterizedBy(source))
            .addSuperclassConstructorParameter("%T::class.java", source)
            .addSuperinterface(MODULE_LOADER)
            .addFunction(module("addSerializer", source))
            .addFunction(
                FunSpec.builder("serialize")
                    .addModifiers(KModifier.OVERRIDE)
                    .addParameter("value", source)
                    .addParameter("gen", JSON_GENERATOR)
                    .addParameter("serializers", SERIALIZER_PROVIDER)
                    .addCode(serializeBody(model))
                    .build()
            )
        val reflected = model.properties.filterNot { it.accessible }
        if (reflected.isNotEmpty()) {
            type.addType(
                TypeSpec.companionObjectBuilder().addModifiers(KModifier.PRIVATE)
                    .addProperties(reflected.map { reflectedProperty(source, it) })
                    .build()
            )
        }
        return FileSpec.builder(name).addType(type.build()).build()
    }

    private fun module(method: String, source: ClassName): FunSpec =
        FunSpec.builder("module")
            .addModifiers(KModifier.OVERRIDE)
            .returns(MODULE)
            .addStatement("return %T().$method(%T::class.java, this)", SIMPLE_MODULE, source)
            .build()

    private fun reflectedProperty(source: ClassName, property: JacksonPropertyModel): PropertySpec {
        val propertyType = K_PROPERTY1.parameterizedBy(source, property.type)
        return PropertySpec.builder(property.reflectedProperty, propertyType, KModifier.PRIVATE)
            .delegate(
                CodeBlock.builder()
                    .beginControlFlow("lazy($LAZY_MODE)")
                    .addStatement("@Suppress(%S)", "UNCHECKED_CAST")
                    .addStatement(
                        "(%T::class.%M.first { it.name == %S } as %T).apply { %M = true }",
                        source,
                        DECLARED_MEMBER_PROPERTIES,
                        property.name,
                        propertyType,
                        IS_ACCESSIBLE,
                    )
                    .endControlFlow()
                    .build()
            )
            .build()
    }

    private fun serializeBody(model: JacksonClassModel): CodeBlock {
        val code = CodeBlock.builder().addStatement("gen.writeStartObject()")
        model.properties.forEach { property ->
            code.addStatement("gen.writeName(%S)", property.jsonName)
            if (property.accessible) {
                code.addStatement("val %N = value.%N", property.local, property.name)
            } else {
                code.addStatement("val %N = %N.get(value)", property.local, property.reflectedProperty)
            }
            if (property.type.isNullable) {
                code.beginControlFlow("if (%N == null)", property.local)
                    .addStatement("gen.writeNull()")
                    .nextControlFlow("else")
            }
            code.add(writeValue(property))
            if (property.type.isNullable) code.endControlFlow()
        }
        return code.addStatement("gen.writeEndObject()").build()
    }

    private fun writeValue(property: JacksonPropertyModel): CodeBlock {
        val writeMethod = property.kind.writeMethod
        val javaType = property.javaType
        return when {
            writeMethod != null -> CodeBlock.of("gen.$writeMethod(%N)\n", property.local)
            javaType != null -> CodeBlock.of(
                "serializers.findTypedValueSerializer(%L, true).serialize(%N, gen, serializers)\n",
                javaType.code(),
                property.local,
            )

            else -> CodeBlock.of("serializers.writeValue(gen, %N)\n", property.local)
        }
    }

    private fun JavaTypeModel.code(): CodeBlock = when (this) {
        is JavaTypeModel.Simple -> CodeBlock.of("serializers.typeFactory.constructType(%T::class.javaObjectType)", rawClass)
        is JavaTypeModel.Collection -> CodeBlock.of(
            "serializers.typeFactory.constructCollectionType(%T::class.java, %L)",
            rawClass,
            element.code(),
        )

        is JavaTypeModel.Map -> CodeBlock.of(
            "serializers.typeFactory.constructMapType(%T::class.java, %L, %L)",
            rawClass,
            key.code(),
            value.code(),
        )
    }

    /** The deserializer source file. */
    fun deserializer(model: JacksonClassModel): FileSpec {
        val source = model.className
        val name = deserializerName(source)
        val constructorProperties = model.properties.filter { it.constructorParameter }
        val companion = TypeSpec.companionObjectBuilder().addModifiers(KModifier.PRIVATE)
        if (constructorProperties.isNotEmpty()) {
            companion.addProperty(
                PropertySpec.builder("primaryConstructor", K_FUNCTION.parameterizedBy(source), KModifier.PRIVATE)
                    .delegate("lazy($LAZY_MODE) { %T::class.%M!! }", source, PRIMARY_CONSTRUCTOR)
                    .build()
            )
            companion.addProperty(
                PropertySpec.builder("parameters", MAP.parameterizedBy(STRING, K_PARAMETER), KModifier.PRIVATE)
                    .delegate(
                        CodeBlock.builder()
                            .add("lazy($LAZY_MODE) {\n⇥mapOf(\n⇥")
                            .apply {
                                constructorProperties.forEach {
                                    add("%S to primaryConstructor.%M(%S)!!,\n", it.name, FIND_PARAMETER_BY_NAME, it.name)
                                }
                            }
                            .add("⇤)\n⇤}")
                            .build()
                    )
                    .build()
            )
        }
        model.deserializedProperties
            .filter { it.kind.readProperty == null && it.type.copy(nullable = false) is ParameterizedTypeName }
            .forEach {
                val referenceType = TYPE_REFERENCE.parameterizedBy(it.type.copy(nullable = false))
                companion.addProperty(
                    PropertySpec.builder(it.reference, referenceType, KModifier.PRIVATE)
                        .initializer("object : %T() {}", referenceType)
                        .build()
                )
            }

        val type = TypeSpec.classBuilder(name)
            .addModifiers(KModifier.INTERNAL)
            .superclass(JSON_DESERIALIZER.parameterizedBy(source))
            .addSuperinterface(MODULE_LOADER)
            .addFunction(module("addDeserializer", source))
            .addFunction(
                FunSpec.builder("deserialize")
                    .addModifiers(KModifier.OVERRIDE)
                    .addParameter("p", JSON_PARSER)
                    .addParameter("ctxt", DESERIALIZATION_CONTEXT)
                    .returns(source)
                    .addCode(deserializeBody(model))
                    .build()
            )
        companion.build().takeIf { it.propertySpecs.isNotEmpty() }?.let { type.addType(it) }
        return FileSpec.builder(name).addType(type.build()).build()
    }

    /** The deserialized properties: the constructor parameters and the writable properties. */
    private val JacksonClassModel.deserializedProperties: List<JacksonPropertyModel>
        get() = properties.filter { it.constructorParameter || it.writable }

    private fun deserializeBody(model: JacksonClassModel): CodeBlock {
        val code = CodeBlock.builder().beginControlFlow("with(p)")
        model.deserializedProperties.forEach {
            code.addStatement("var %N: %T = null", it.local, it.type.copy(nullable = true))
            code.addStatement("var %N: %T = false", it.setFlag, BOOLEAN)
        }
        // a value read with readValueAs leaves the parser on its last token: the next name is after this token
        code.addStatement("var token_: %T = currentToken()", JSON_TOKEN.copy(nullable = true))
            .addStatement("if (token_ == %T.START_OBJECT) token_ = nextToken()", JSON_TOKEN)
            .beginControlFlow("while (token_ == %T.PROPERTY_NAME)", JSON_TOKEN)
            .addStatement("val fieldName_ = currentName()")
            .addStatement("token_ = nextToken()")
            .beginControlFlow("when (fieldName_)")
        model.deserializedProperties.forEach {
            code.beginControlFlow("%S ->", it.jsonName)
                .addStatement("%N = if (token_ == %T.VALUE_NULL) null else %L", it.local, JSON_TOKEN, readValue(it))
                .addStatement("%N = true", it.setFlag)
                .endControlFlow()
        }
        code.beginControlFlow("else ->")
            .addStatement("if (token_?.isStructStart == true) p.skipChildren()")
            .endControlFlow()
            .endControlFlow()
            .addStatement("token_ = nextToken()")
            .endControlFlow()
        code.add(construct(model))
        model.properties.filter { !it.constructorParameter && it.writable }.forEach {
            code.addStatement("if (%N) result_.%N = %L", it.setFlag, it.name, it.localValue())
        }
        return code.addStatement("return result_").endControlFlow().build()
    }

    private fun readValue(property: JacksonPropertyModel): CodeBlock {
        val readProperty = property.kind.readProperty
        val type = property.type.copy(nullable = false)
        return when {
            readProperty != null -> CodeBlock.of("p.$readProperty")
            type is ParameterizedTypeName -> CodeBlock.of("p.readValueAs(%N)", property.reference)
            else -> CodeBlock.of("p.readValueAs(%T::class.javaObjectType)", type)
        }
    }

    private fun JacksonPropertyModel.localValue(): CodeBlock =
        if (type.isNullable) CodeBlock.of("%N", local) else CodeBlock.of("%N!!", local)

    private fun construct(model: JacksonClassModel): CodeBlock {
        val constructorProperties = model.properties.filter { it.constructorParameter }
        val arguments = constructorProperties
            .map { CodeBlock.of("%N = %L", it.name, it.localValue()) }
            .joinToCode()
        if (constructorProperties.isEmpty()) {
            return CodeBlock.of("val result_ = %T()\n", model.className)
        }
        return CodeBlock.builder()
            .add("val result_ = if (%L) {\n⇥", constructorProperties.map { CodeBlock.of("%N", it.setFlag) }.joinToCode(" && "))
            .add("%T(%L)\n", model.className, arguments)
            .add("⇤} else {\n⇥")
            // missing values: the default values of the constructor parameters are used
            .addStatement("val map_ = mutableMapOf<%T, %T>()", K_PARAMETER, ANY.copy(nullable = true))
            .apply {
                constructorProperties.forEach {
                    addStatement("if (%N) map_[parameters.getValue(%S)] = %N", it.setFlag, it.name, it.local)
                }
            }
            .addStatement("primaryConstructor.callBy(map_)")
            .add("⇤}\n")
            .build()
    }
}
