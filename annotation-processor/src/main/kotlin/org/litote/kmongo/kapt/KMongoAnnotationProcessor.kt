/**
 * KAPT (JSR 269) version of the `kmongo-dsl-ksp` processor: generates the type-safe property paths
 * (`MyClass_`, `MyClass_Col`, `MyClass_Map`) for the Kotlin classes annotated with `@Data`
 * (or listed in a `@DataRegistry`).
 *
 * The generated code is the same as the code generated by `kmongo-dsl-ksp` (the generation is shared).
 * Use it with the `kapt` goal of the `kotlin-maven-plugin` (KSP has no official Maven plugin) or
 * with the `kotlin-kapt` Gradle plugin - KSP is recommended with Gradle.
 *
 * The Kotlin properties of the classes are read from their Kotlin metadata (`kotlin-metadata-jvm`).
 */
@SupportedOptions(KAPT_KOTLIN_GENERATED_OPTION)
public class KMongoAnnotationProcessor : AbstractProcessor() {

    private companion object {
        val DATA_ANNOTATIONS = listOf("org.litote.kmongo.Data", "org.litote.jackson.data.JacksonData")
        val REGISTRY_ANNOTATIONS =
            listOf("org.litote.kmongo.DataRegistry", "org.litote.jackson.data.JacksonDataRegistry")
        const val PATHS_RUNTIME_CLASS = "org.litote.kmongo.property.KPropertyPath"
    }

    /**
     * The `@JacksonData` classes are processed only if the property paths runtime (`kmongo-dsl-core`) is in the classpath:
     * a module using `@JacksonData` only for the Jackson serializers (`kmongo-dsl-annotation-generator`) does not
     * depend on kmongo-dsl (as with `kmongo-annotation-processor`, which processed only `@Data`).
     */
    private val jacksonDataSupported: Boolean by lazy {
        processingEnv.elementUtils.getTypeElement(PATHS_RUNTIME_CLASS) != null
    }

    private val dataAnnotations: List<String>
        get() = if (jacksonDataSupported) DATA_ANNOTATIONS else DATA_ANNOTATIONS.take(1)

    private val registryAnnotations: List<String>
        get() = if (jacksonDataSupported) REGISTRY_ANNOTATIONS else REGISTRY_ANNOTATIONS.take(1)

    /**
     * A class whose property paths are generated.
     */
    private class DataClass(val element: TypeElement, val internal: Boolean)

    /** Generated class name -> source class qualified name (all rounds). */
    private val generated = mutableMapOf<String, String>()

    override fun getSupportedAnnotationTypes(): Set<String> = (DATA_ANNOTATIONS + REGISTRY_ANNOTATIONS).toSet()

    override fun getSupportedSourceVersion(): SourceVersion = SourceVersion.latestSupported()

    override fun process(annotations: Set<TypeElement>, roundEnv: RoundEnvironment): Boolean {
        if (annotations.isEmpty()) return false

        val dataClasses = linkedMapOf<String, DataClass>()
        val registered = mutableSetOf<String>()

        fun register(element: TypeElement, internal: Boolean) {
            dataClasses.getOrPut(element.qualifiedName.toString()) { DataClass(element, internal) }
            // superclasses are registered too
            element.superclassElement()?.let { register(it, internal) }
        }

        dataAnnotations.forEach { annotationName ->
            val annotation = processingEnv.elementUtils.getTypeElement(annotationName) ?: return@forEach
            roundEnv.getElementsAnnotatedWith(annotation)
                .filterIsInstance<TypeElement>()
                .forEach { register(it, it.findAnnotation(annotationName).booleanArgument("internal")) }
        }
        registryAnnotations.forEach { annotationName ->
            val annotation = processingEnv.elementUtils.getTypeElement(annotationName) ?: return@forEach
            roundEnv.getElementsAnnotatedWith(annotation).forEach { registry ->
                val mirror = registry.findAnnotation(annotationName)
                val internal = mirror.booleanArgument("internal")
                mirror.classesArgument("value").forEach { element ->
                    registered += element.qualifiedName.toString()
                    register(element, internal)
                }
            }
        }

        // the classes compiled with the generated code (their internal properties are accessible)
        val sources = roundEnv.rootElements.filterIsInstance<TypeElement>().map { it.qualifiedName.toString() }.toSet()
        val context = Context(dataClasses.keys + registered, sources)
        dataClasses.values
            .filter { checkNameCollision(it) }
            .forEach { dataClass ->
                @Suppress("TooGenericExceptionCaught")
                try {
                    context.model(dataClass)?.let { processingEnv.writeKotlin(PropertyPathGenerator.generate(it)) }
                } catch (e: Exception) {
                    error("KMongo: unable to generate property paths for ${dataClass.element.qualifiedName}: $e", dataClass.element)
                }
            }
        return false
    }

    /**
     * Returns true if the generated classes of [dataClass] have to be generated (ie not already generated),
     * reports an error if another class has the same generated class name.
     */
    private fun checkNameCollision(dataClass: DataClass): Boolean {
        val qualifiedName = dataClass.element.qualifiedName.toString()
        val generatedName = PropertyPathGenerator.generatedName(dataClass.element.kotlinClassName()).canonicalName
        return when (val previous = generated.putIfAbsent(generatedName, qualifiedName)) {
            null -> true
            qualifiedName -> false
            else -> {
                error(
                    "KMongo: $qualifiedName and $previous have the same generated class name $generatedName " +
                            "(nested classes with the same simple name in the same package are not supported)",
                    dataClass.element
                )
                false
            }
        }
    }

    private fun error(message: String, element: Element) {
        processingEnv.messager.printMessage(Diagnostic.Kind.ERROR, message, element)
    }

    /**
     * The model builder.
     *
     * @param dataClassNames the qualified names of the processed and registered data classes
     */
    private inner class Context(val dataClassNames: Set<String>, val sourceClassNames: Set<String>) {

        fun model(dataClass: DataClass): DataClassModel? {
            val element = dataClass.element
            val kmClass = element.kmClass()
            if (kmClass == null) {
                error("KMongo: ${element.qualifiedName} is not a Kotlin class", element)
                return null
            }
            return DataClassModel(
                className = kmClass.name.toClassName(),
                typeParameterCount = kmClass.typeParameters.size,
                internal = dataClass.internal,
                open = kmClass.modality == Modality.OPEN || kmClass.modality == Modality.ABSTRACT
                        || kmClass.modality == Modality.SEALED,
                dataSuperclass = element.superclassElement()?.takeIf { isData(it) }?.kotlinClassName(),
                properties = kmClass.properties
                    .filter { it.receiverParameterType == null && it.kind == MemberKind.DECLARATION }
                    .map { property(it, element.outermostClass().qualifiedName.toString() in sourceClassNames) },
            )
        }

        private fun TypeElement.outermostClass(): TypeElement = (enclosingElement as? TypeElement)?.outermostClass() ?: this

        /**
         * @param fromSources true if the class is compiled with the generated code
         */
        private fun property(property: KmProperty, fromSources: Boolean): DataPropertyModel {
            val type = property.returnType
            val className = type.qualifiedClassName()
            val kind = when {
                className == "kotlin.collections.Iterable" || processingEnv.isSubtypeOf(className, "java.util.Collection") ->
                    PropertyKind.COLLECTION
                processingEnv.isSubtypeOf(className, "java.util.Map") -> PropertyKind.MAP
                else -> PropertyKind.SIMPLE
            }
            fun KmType?.dataClass(): ClassName? =
                this?.qualifiedClassName()?.let { processingEnv.typeElement(it) }?.takeIf { isData(it) }?.kotlinClassName()
            return DataPropertyModel(
                name = property.name,
                type = type.toTypeName(),
                // not accessible from the generated code: private, protected or internal in another module
                private = when (property.visibility) {
                    Visibility.PUBLIC -> false
                    Visibility.INTERNAL -> !fromSources
                    else -> true
                },
                kind = kind,
                dataClass = when (kind) {
                    PropertyKind.SIMPLE -> type.dataClass()
                    PropertyKind.COLLECTION -> type.arguments.getOrNull(0)?.type.dataClass()
                    PropertyKind.MAP -> type.arguments.getOrNull(1)?.type.dataClass()
                },
            )
        }

        private fun isData(element: TypeElement): Boolean =
            element.qualifiedName.toString() in dataClassNames
                    || dataAnnotations.any { element.findAnnotation(it) != null }
    }
}
