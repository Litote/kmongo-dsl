package org.litote.kmongo.golden

import org.bson.BsonDocument
import org.bson.BsonDocumentReader
import org.bson.BsonDocumentWriter
import org.bson.codecs.Codec
import org.bson.codecs.DecoderContext
import org.bson.codecs.EncoderContext
import org.litote.kmongo.service.ClassMappingType
import org.litote.kmongo.util.KMongoUtil
import org.litote.kmongo.util.ObjectMappingConfiguration
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.fail

/**
 * Checks that kmongo-dsl writes and reads the same BSON documents than KMongo 5.12
 * (the golden files are generated by the kmongo-dsl-golden project).
 *
 * Compiled in the kmongo-dsl mapping modules tests.
 */
abstract class AbstractGoldenFormatTest(private val mapping: String, private val serialization: Boolean) {

    /** Known (and documented) format differences: golden file name -> reason. */
    open val knownDifferences: Map<String, String> = emptyMap()

    @AfterTest
    fun resetConfiguration() {
        ObjectMappingConfiguration.serializeNull = true
    }

    @Test
    fun `kmongo-dsl writes and reads the KMongo 5 documents`() {
        val registry = ClassMappingType.codecRegistry(KMongoUtil.defaultCodecRegistry)
        val errors = mutableListOf<String>()
        for (serializeNull in listOf(true, false)) {
            ObjectMappingConfiguration.serializeNull = serializeNull
            goldenSamples(serialization).forEach { (name, value) ->
                val fileName = goldenFileName(name, serializeNull)
                if (fileName in knownDifferences) return@forEach
                val golden = BsonDocument.parse(
                    javaClass.getResource("/golden/$mapping/$fileName")?.readText()
                        ?: error("golden file $fileName not found")
                )
                @Suppress("UNCHECKED_CAST")
                val codec = registry.get(value.javaClass) as Codec<Any>
                val document = BsonDocument()
                try {
                    codec.encode(BsonDocumentWriter(document), value, EncoderContext.builder().build())
                    if (document != golden) {
                        errors += "$fileName: written document differs\n  expected ${golden.toJson()}\n  actual   ${document.toJson()}"
                    }
                } catch (e: Exception) {
                    errors += "$fileName: write error $e"
                }
                try {
                    val decoded = codec.decode(BsonDocumentReader(golden), DecoderContext.builder().build())
                    if (decoded != value) {
                        errors += "$fileName: read value differs\n  expected $value\n  actual   $decoded"
                    }
                } catch (e: Exception) {
                    errors += "$fileName: read error $e"
                }
            }
        }
        if (errors.isNotEmpty()) fail(errors.joinToString("\n"))
    }
}

